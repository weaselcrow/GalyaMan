// Экран 800x450. Пол на высоте FY (386). Чем меньше y, тем выше.
// Галя прыгает вверх примерно на 90 и вдаль примерно на 130.
// Уровень открывается в меню, когда пройден предыдущий.
// Чтобы открыть всё для проверки, в консоли браузера: localStorage.galyamen_unlocked = 99

LEVELS.push({
  name: 'НАЗВАНИЕ УРОВНЯ',
  sub: 'пара слов для меню',
  author: 'твоё имя',
  boss: false,                 // true: после ворот будет бой с Пушистиком
  build() {
    const k = levelKit(3000);  // длина уровня в пикселях, ворота встанут в самом конце

    // пол: от x до x. Разрыв между кусками пола становится ямой с шипами
    k.fl(-200, 1200);
    k.fl(1300, 3200);

    k.bl(600, 346, 70, 40);            // ящик: x, y верха, ширина, высота
    k.pl(900, 320, 80);                // платформа: x, y, ширина (на неё можно запрыгнуть снизу)
    k.mv(1700, 1820, 330, 84, 45);     // платформа, которая ездит: от x, до x, y, ширина, скорость
    k.spikes(1500, 50);                // шипы на полу: x, ширина
    k.zap(2100, 200);                  // разряд: x, y верхнего излучателя
    k.check(1400);                     // сохранение
    k.sign(80, 240, ['ПРИВЕТ', 'ЭТО МОЙ УРОВЕНЬ']);   // табличка: x, y, строки

    // кролики: x, y (на чём стоит), тип, реплика
    // типы: 'sit' сидит и дрожит, 'give' протягивает морковку, 'run' убегает
    k.rb(400, FY, 'sit', 'привет!');
    k.rb(635, 346, 'give', 'это тебе');          // стоит на ящике: y = y верха ящика
    k.rb(1000, FY, 'run', 'А-А-А!');
    k.rb(2300, FY, 'sit', 'мы за мир!', { sign: 'МИР' });   // с плакатом
    k.rb(2400, FY, 'sit', 'я маленький', { scale: .6 });    // маленький

    // чемоданы: x, y, что внутри, цвет 0..4
    // внутри: 'socks', 'heart', 'carrots', 'hats', 'matryoshka', 'rabbit', 'letter'
    k.cs(300, FY, 'heart', 1);

    k.deco(1100, 2);                   // чемодан для красоты (не открывается)

    // необязательное
    k.l.iceX = 1600;                   // где проезжает мороженщик
    k.l.fallX = 2500;                  // где с неба падает чемодан
    k.l.pot = { x: 940, y: 320 };      // кастрюля с рагу (лечит полностью)

    return k.done();
  }
});
